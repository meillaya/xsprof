#!/bin/sh
# Strict perf-script importer gate.
#
# Two levels, both fail closed:
#
#   1. parser / fixture level (always runs): copy the importer's import closure
#      into a throwaway module tree and run `zig test` on a generated root that
#      pulls in the module's own tests and adds two on-disk fixture checks
#      (accept two lines -> canonical events, reject three lines -> bounded
#      diagnostics with line numbers). The throwaway tree exists because a bare
#      `zig test src/viz/perf_script_import.zig` cannot import `../core/event.zig`
#      (Zig module roots are directory-scoped); the copies are byte-identical.
#
#   2. CLI level (runs when wired): if the built binary exposes the hidden
#      `import` verb, the fixtures are pushed through the real CLI, the accepted
#      rows are validated against `schemas/xsprof/event.v1.schema.json`, and the
#      rejected fixture must exit non-zero with no output rows. Until the Lead
#      wires the verb this level prints an explicit SKIP with the exact command
#      that would make it a real gate -- it never reports a fake full PASS.
#
# No privileges, no network, no display, no recorder state: temporary files only.
#
# Usage: sh qa/import_smoke.sh [--help]
# Exit:  0 PASS (parser/fixture checks passed; CLI level PASS or explicit SKIP),
#        1 assertion/setup failure, 2 usage error.
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
BIN=${XSPROF_BIN:-"$ROOT/zig-out/bin/xsprof"}
ZIG=${XSPROF_ZIG_BIN:-"$ROOT/tools/zig"}
TMP=
trap 'if [ -n "$TMP" ]; then rm -rf "$TMP"; fi' EXIT HUP INT TERM

usage() {
    cat <<'EOF'
Usage: sh qa/import_smoke.sh [--help]

Gate the strict perf-script -> xsprof/event/v1 importer:
  - parser unit tests and two on-disk fixtures run through `zig test`
  - when the CLI exposes the hidden `import` verb, the same fixtures run
    end-to-end (accept validates against event.v1; reject exits non-zero)
  - otherwise the CLI level prints SKIP with the command required to wire it

Environment:
  XSPROF_BIN      xsprof binary to probe (default: <repo>/zig-out/bin/xsprof)
  XSPROF_ZIG_BIN  Zig launcher (default: <repo>/tools/zig)

Exit: 0 PASS (parser/fixtures; CLI PASS or explicit CLI SKIP), 1 failure, 2 usage.
EOF
}

fail() {
    echo "import_smoke: FAIL: $*" >&2
    exit 1
}

note() {
    echo "import_smoke: $*"
}

# The fixtures below use the documented default `perf script` layout (see the
# module docs in src/viz/perf_script_import.zig): comm/tid/cpu/timestamp,
# event name, then the tracepoint TP_printk payload.
write_accept_fixture() { # PATH
    cat >"$1" <<'EOF'
# perf script fixture: sched_switch / sched_wakeup, default header fields
     swapper/1     0 [001] 1000.000001: sched:sched_switch: prev_comm=swapper/1 prev_pid=0 prev_prio=120 prev_state=R ==> next_comm=worker next_pid=4242 next_prio=120
           driver  4241 [002] 1000.000002: sched:sched_wakeup: comm=worker pid=4242 prio=120 target_cpu=002
     swapper/2     0 [000] 1000.000003: sched:sched_switch: prev_comm=swapper/2 prev_pid=0 prev_prio=120 prev_state=R+ ==> next_comm=worker next_pid=4242 next_prio=120
           worker  4242 [000] 1000.000004: sched:sched_switch: prev_comm=worker prev_pid=4242 prev_prio=120 prev_state=S ==> next_comm=idle next_pid=0 next_prio=120
EOF
}

# Line 1 is valid; line 2 is an unsupported tracepoint; line 3 is missing a
# payload field; line 4 has no timestamp. A fail-closed importer must count 3
# rejected lines and name lines 2, 3, and 4.
write_reject_fixture() { # PATH
    cat >"$1" <<'EOF'
     swapper/1     0 [001] 1000.000001: sched:sched_switch: prev_comm=swapper/1 prev_pid=0 prev_prio=120 prev_state=R ==> next_comm=worker next_pid=4242 next_prio=120
           worker  4242 [002] 1000.000002: sched:sched_migrate_task: comm=worker pid=4242 prio=120 orig_cpu=2 dest_cpu=3
           worker  4242 [002] 1000.000003: sched:sched_wakeup: comm=worker pid=4242 target_cpu=002
           worker  4242 [002] garbage
EOF
}

copy_module() { # SRC_FIXTURE_DIR DEST_SRC_DIR
    fixtures=$1
    dest=$2
    mkdir -p "$dest/core" "$dest/viz"
    # The importer imports only core/event.zig, whose closure is json.zig and
    # privacy.zig. Copying the whole core directory keeps the closure correct
    # if it grows, and the generated root compiles only what is reachable.
    cp "$ROOT"/src/core/*.zig "$dest/core/" || fail "cannot copy src/core into the test module"
    cp "$ROOT/src/viz/perf_script_import.zig" "$dest/viz/" ||
        fail "cannot copy src/viz/perf_script_import.zig into the test module"
    cp "$fixtures/accept.perf" "$dest/accept.perf"
    cp "$fixtures/reject.perf" "$dest/reject.perf"
}

write_test_root() { # TREE_SRC_DIR
    src=$1
    cat >"$src/root.zig" <<'EOF'
//! Generated by qa/import_smoke.sh: throwaway test root for the importer.
//! The module under test keeps its real `src/viz/../core/...` imports; this
//! root only exists so a bare `zig test` has a directory-scoped module root.
const std = @import("std");
const imp = @import("viz/perf_script_import.zig");

test {
    _ = imp;
}

test "fixture accept file converts to canonical events" {
    const result = try imp.import(std.testing.allocator, @embedFile("accept.perf"), .{});
    defer result.deinit(std.testing.allocator);
    try std.testing.expect(result.ok());
    try std.testing.expectEqual(@as(u64, 4), result.accepted);
    try std.testing.expectEqual(@as(u64, 0), result.rejected);
    try std.testing.expectEqual(@as(usize, 4), result.events.len);
    // Row 1: switch-out of swapper/1, switch-in worker:4242 => a=4242, b=0.
    try std.testing.expectEqual(@as(u64, 4242), result.events[0].a);
    try std.testing.expectEqual(@as(u64, 0), result.events[0].b);
    try std.testing.expectEqual(@as(u64, 1_000_000_001_000), result.events[0].ts_ns);
    // Row 2: wakeup of worker:4242 on CPU 2 => a=4242, b=2.
    try std.testing.expectEqual(@as(u64, 4242), result.events[1].a);
    try std.testing.expectEqual(@as(u64, 2), result.events[1].b);
    // Row 3: R+ (preempted) is normalized to the canonical running marker.
    try std.testing.expectEqual(@as(u64, 0), result.events[2].c);
}

test "fixture reject file fails closed with line numbers" {
    const result = try imp.import(std.testing.allocator, @embedFile("reject.perf"), .{});
    defer result.deinit(std.testing.allocator);
    try std.testing.expect(!result.ok());
    try std.testing.expectEqual(@as(u64, 1), result.accepted);
    try std.testing.expectEqual(@as(u64, 3), result.rejected);
    try std.testing.expectEqual(@as(usize, 3), result.diagnostics.len);
    try std.testing.expectEqual(@as(u64, 2), result.diagnostics[0].line);
    try std.testing.expectEqual(imp.Reason.unsupported_event, result.diagnostics[0].reason);
    try std.testing.expectEqual(@as(u64, 3), result.diagnostics[1].line);
    try std.testing.expectEqual(imp.Reason.bad_payload, result.diagnostics[1].reason);
    try std.testing.expectEqual(@as(u64, 4), result.diagnostics[2].line);
    try std.testing.expectEqual(imp.Reason.bad_header, result.diagnostics[2].reason);
}
EOF
}

run_parser_tests() { # TREE
    tree=$1
    export ZIG_GLOBAL_CACHE_DIR=${ZIG_GLOBAL_CACHE_DIR:-"$ROOT/.zig-cache/global"}
    export ZIG_LOCAL_CACHE_DIR=${ZIG_LOCAL_CACHE_DIR:-"$ROOT/.zig-cache"}
    log="$TMP/zig-test.log"
    if ! "$ZIG" test "$tree/src/root.zig" >"$log" 2>&1; then
        if [ -s "$log" ]; then
            sed -n '1,40p' "$log" >&2
        fi
        fail "parser unit/fixture tests failed (see test output above)"
    fi
    if grep -q 'All [0-9]* tests passed' "$log"; then
        note "parser unit + fixture tests: PASS ($(grep -o 'All [0-9]* tests passed' "$log" | head -1))"
    else
        note "parser unit + fixture tests: PASS"
    fi
}

# cli_wired reports whether the built binary exposes the hidden `import` verb.
cli_wired() {
    [ -x "$BIN" ] || return 1
    "$BIN" help --json --all 2>/dev/null | grep -q '"name":"import"' || return 1
    return 0
}

run_cli_checks() {
    accept=$1
    reject=$2
    out="$TMP/cli-accept.ndjson"
    err="$TMP/cli-accept.err"

    if ! "$BIN" import --perf-script "$accept" >"$out" 2>"$err"; then
        sed -n '1,10p' "$err" >&2 || true
        fail "CLI import refused the accepted fixture (wiring/flags differ from the documented interface)"
    fi
    [ -s "$out" ] || fail "CLI import wrote no canonical rows for the accepted fixture"
    lines=$(wc -l <"$out" | tr -d ' ')
    [ "$lines" -eq 4 ] || fail "CLI import wrote $lines rows for a 4-line fixture"
    "$BIN" validate --schema event.v1 --file "$out" --json >"$TMP/cli-validate.json" 2>"$TMP/cli-validate.err" ||
        fail "imported rows do not validate against event.v1 (see validate output above)"
    grep -q '"ok":true' "$TMP/cli-validate.json" || fail "validate did not report ok:true"
    if grep -v '"host_mutation":false' "$out" | grep -q .; then
        fail "imported rows contain host_mutation=true"
    fi
    note "cli: accepted fixture -> 4 canonical rows, schema-valid, host_mutation=false"

    rej_out="$TMP/cli-reject.ndjson"
    rej_err="$TMP/cli-reject.err"
    status=0
    "$BIN" import --perf-script "$reject" >"$rej_out" 2>"$rej_err" || status=$?
    [ "$status" -ne 0 ] || fail "CLI import accepted the rejected fixture (must fail closed)"
    if [ -s "$rej_out" ]; then
        fail "CLI import emitted partial rows for a fail-closed rejection"
    fi
    note "cli: rejected fixture -> exit $status, no output rows (fail closed)"
}

main() {
    while [ "$#" -gt 0 ]; do
        case "$1" in
            -h | --help)
                usage
                return 0
                ;;
            *)
                usage >&2
                return 2
                ;;
        esac
    done

    [ -x "$ZIG" ] || fail "Zig launcher not found: $ZIG"
    TMP=$(mktemp -d "${TMPDIR:-/tmp}/xsprof-import-smoke.XXXXXX") ||
        fail "cannot create a temporary directory"

    write_accept_fixture "$TMP/accept.perf"
    write_reject_fixture "$TMP/reject.perf"

    tree="$TMP/module"
    copy_module "$TMP" "$tree/src"
    write_test_root "$tree/src"
    run_parser_tests "$tree"

    if cli_wired; then
        run_cli_checks "$TMP/accept.perf" "$TMP/reject.perf"
        note "PASS (parser unit+fixture; CLI import end-to-end)"
        return 0
    fi
    if [ ! -x "$BIN" ]; then
        note "SKIP cli: binary not found: $BIN (build with ./tools/zig build)"
    else
        note "SKIP cli: the binary has no 'import' verb yet; end-to-end gate requires:"
        note "          xsprof import --perf-script FILE   (canonical NDJSON on stdout)"
    fi
    note "PASS (parser unit+fixture; CLI level not wired -- see SKIP line above)"
    return 0
}

main "$@"
